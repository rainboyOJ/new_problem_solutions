import sys
from functools import lru_cache


@lru_cache(maxsize=None)
def d(n: int) -> int:
    """n! 去掉所有因子 10（即末尾 0）后的个位数字。

    递推：D(n) = D(n//5) * D(n%5) * 2^(n//5) mod 10。
    - 每 5 个数提出一个因子 5，与偶数配对成一个 10，把因子 5 全部消掉；
    - 消掉这轮 5 的同时，每 5 个数还剩下 2、4、6、8 各一个，
      乘积 2*4*6*8 ≡ 2^4 ≡ 1 (mod 10)，只余下「5 的倍数之外的那个残数」；
    - 商 q = n//5 继续递归（里面还有 5 的倍数），其贡献相当于多乘 2^q。
    """
    if n < 5:
        return (1, 1, 2, 6, 4)[n]
    q, r = divmod(n, 5)
    # (1,2,4,8)[q%4] 即 2^q 的个位（q≥1 时 2^q 个位按 2,4,8,6 循环，q%4=0 时为 6，但此处 q≥1 故 2^0=1 不会误触发）
    return d(q) * (1, 1, 2, 6, 4)[r] * (1, 2, 4, 8)[q % 4] % 10


print(d(int(sys.stdin.read())))
